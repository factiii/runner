import { z } from 'zod';

// The Vault's key (.specs/vault.md "Encryption and the Vault key"): what a
// device sends its runner to set encryption up, unlock, lock and change the
// Vault key. Checked on the runner before any key is touched, and used by
// the client to build the same payloads. Every one of these is a vault
// action: refused on the relay (RELAY_VAULT_REFUSAL), owner only.

/** The runner's answer to any Vault action while the Vault is locked: one
 *  string the app matches (`isVaultLocked`), and the result's `code`. */
export const VAULT_LOCKED =
  'Your Vault is locked. Unlock it with your Vault key.';
export const VAULT_LOCKED_CODE = 'VAULT_LOCKED';

/** Is this error the runner's locked-Vault answer? */
export const isVaultLocked = (message: string | null | undefined): boolean =>
  message?.startsWith(VAULT_LOCKED) ?? false;

/** The runner's answer to a Vault key that does not open the Vault: the app
 *  matches it to drop a remembered copy that went stale (the key was
 *  changed on another device). */
export const WRONG_VAULT_KEY =
  'That Vault key does not open this Vault. Check it, or fill it from your password manager.';

export const isWrongVaultKey = (message: string | null | undefined): boolean =>
  message?.startsWith(WRONG_VAULT_KEY) ?? false;

/** Idle minutes before the runner locks the Vault (VAULT_LOCK_IDLE_MINUTES). */
export const VAULT_LOCK_IDLE_MINUTES = 15;
export const VAULT_LOCK_IDLE_MINUTES_MIN = 1;
export const VAULT_LOCK_IDLE_MINUTES_MAX = 24 * 60;

/** The Vault key: generated by the runner, 32 Crockford base32 characters
 *  (160 bits), shown in 8 groups of 4 for the password manager. Typed back
 *  with any spacing, dashes or case. */
export const VAULT_KEY_CHARS = 32;
export const VAULT_KEY_GROUP_CHARS = 4;
/** No I, L, O or U: nothing to misread. */
export const VAULT_KEY_ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
const vaultKey = z.string().trim().min(VAULT_KEY_CHARS).max(80);

/** How long a new Vault key the runner showed waits to be confirmed. */
export const VAULT_KEY_PENDING_MS = 15 * 60_000;

/** Unlock: the Vault key, on the direct link only. */
export const vaultUnlockSchema = z.object({ vaultKey });
export type VaultUnlockInput = z.infer<typeof vaultUnlockSchema>;

/** Confirm a new Vault key the runner showed (setup, or a change): the key
 *  typed or filled back, so the Vault is never sealed under a key nobody
 *  kept. */
export const vaultKeyConfirmSchema = z.object({
  pendingId: z.string().uuid(),
  vaultKey
});
export type VaultKeyConfirmInput = z.infer<typeof vaultKeyConfirmSchema>;

/** Start a change: the current key, or nothing while the Vault is unlocked. */
export const vaultKeyChangeStartSchema = z.object({
  vaultKey: vaultKey.optional()
});

export const vaultKeySettingsSchema = z.object({
  lockIdleMinutes: z
    .number()
    .int()
    .min(VAULT_LOCK_IDLE_MINUTES_MIN)
    .max(VAULT_LOCK_IDLE_MINUTES_MAX)
});

/** The Vault key's canonical characters, or null when it cannot be one:
 *  case, spaces and dashes dropped, look-alikes mapped (I and L to 1, O to
 *  0). */
export function normalizeVaultKey(typed: string): string | null {
  const chars = typed
    .toUpperCase()
    .replace(/[\s-]/g, '')
    .replace(/[IL]/g, '1')
    .replace(/O/g, '0');
  if (chars.length !== VAULT_KEY_CHARS) return null;
  return [...chars].every((char) => VAULT_KEY_ALPHABET.includes(char))
    ? chars
    : null;
}

/** The key as shown and saved: groups of four joined by dashes. */
export const formatVaultKey = (canonical: string): string =>
  canonical.match(new RegExp(`.{1,${VAULT_KEY_GROUP_CHARS}}`, 'g'))?.join('-') ??
  canonical;
