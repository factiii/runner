import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { VAULT_MIGRATIONS } from './migrations.generated';
import { pruneSchema } from './schemaGen';

// `pnpm --filter @factiii/runner vault:schema`: cut the server's schema down
// to the vault (schemaGen.ts), write it to vault.prisma, and have Prisma write
// the SQL that takes the last vault.prisma to the new one. Each run that
// changes something appends one migration; one that changes nothing writes
// nothing. `--check` only says whether vault.prisma is behind the server.

const HERE = __dirname;
const REPO = path.resolve(HERE, '../../../..');
const SERVER_SCHEMA = path.join(REPO, 'apps/server/prisma/schema.prisma');
// The vault-only schema lives with the router that queries it (.specs/vault-router.md).
const VAULT_SCHEMA = path.join(REPO, 'shared/vault-router/vault.prisma');
const MIGRATIONS = path.join(HERE, 'migrations.generated.ts');
const PRISMA = path.join(REPO, 'node_modules/.bin/prisma');

/** Prisma's SQL from one schema to another. `from` null is an empty database.
 *  Prisma needs a config file and a URL it never dials; a failed diff
 *  answers nothing at all, so an empty answer is an error here. */
function diff(from: string | null, to: string): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vault-schema-'));
  try {
    fs.writeFileSync(path.join(dir, 'to.prisma'), to);
    if (from !== null) fs.writeFileSync(path.join(dir, 'from.prisma'), from);
    fs.writeFileSync(
      path.join(dir, 'prisma.config.mjs'),
      'export default { schema: "to.prisma", datasource: { url: "postgresql://none:none@localhost:1/none" } };\n'
    );
    const out = execFileSync(
      PRISMA,
      [
        'migrate',
        'diff',
        from === null ? '--from-empty' : '--from-schema=from.prisma',
        '--to-schema=to.prisma',
        '--script',
        '--config=prisma.config.mjs'
      ],
      { cwd: dir, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] }
    );
    const sql = out.replace(/^Loaded Prisma config.*\n/m, '').trim();
    if (!sql) throw new Error('Prisma returned no SQL. Run `prisma validate` on vault.prisma.');
    return sql;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/** Prisma's answer when nothing changed. */
const EMPTY = /^-- This is an empty migration\.?$/;

function main(): void {
  const next = pruneSchema(fs.readFileSync(SERVER_SCHEMA, 'utf-8'));
  const last = fs.existsSync(VAULT_SCHEMA)
    ? fs.readFileSync(VAULT_SCHEMA, 'utf-8')
    : null;
  if (process.argv.includes('--check')) {
    if (last !== next) {
      console.error('vault.prisma is behind the server schema. Run vault:schema.');
      process.exit(1);
    }
    console.log('vault.prisma matches the server schema.');
    return;
  }
  const sql = diff(VAULT_MIGRATIONS.length > 0 ? last : null, next);
  if (EMPTY.test(sql)) {
    // No SQL to run, but the text moved (a comment, the column alignment):
    // vault.prisma still follows it, or the drift check never passes.
    if (last !== next) {
      fs.writeFileSync(VAULT_SCHEMA, next);
      console.log('No migration; vault.prisma updated.');
      return;
    }
    console.log('No change.');
    return;
  }
  const id = `${String(VAULT_MIGRATIONS.length + 1).padStart(4, '0')}_${
    VAULT_MIGRATIONS.length === 0 ? 'init' : new Date().toISOString().slice(0, 10)
  }`;
  const migrations = [...VAULT_MIGRATIONS, { id, sql }];
  fs.writeFileSync(VAULT_SCHEMA, next);
  fs.writeFileSync(
    MIGRATIONS,
    [
      '// GENERATED by `pnpm --filter @factiii/runner vault:schema`. Do not edit.',
      '// Each entry is the SQL Prisma wrote from the vault.prisma before it to the',
      '// one after it; the runner applies the ones it has not run, in order.',
      '',
      'export const VAULT_MIGRATIONS: { id: string; sql: string }[] = [',
      ...migrations.map(
        (m) => `  {\n    id: ${JSON.stringify(m.id)},\n    sql: ${JSON.stringify(m.sql)}\n  },`
      ),
      '];',
      ''
    ].join('\n')
  );
  console.log(`Wrote ${id}.`);
}

main();
