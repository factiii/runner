// The runner vault's schema is the Factiii server's, cut down to the vault
// tables (.specs/runner-vault.md "Database"). This reads the server's
// schema.prisma and keeps the vault models as they are written there, so a
// column added on the server shows up here on the next run and the same SQL
// runs on both. Nothing is typed in by hand: `vault:schema` writes
// vault.prisma from this, and Prisma writes the SQL from vault.prisma.

/** Files (Post + PostContent), uploads, vectors, synced folders and the
 *  share table: the card's "files, uploads, vectors, permissions". Then a
 *  file's categories, as the cloud keeps them: a tag per category
 *  (PostFactiiiCount, its PostFactiii) and the place or date it read
 *  (SpaceTime). The categories themselves (Factiii) stay on Factiii: a tag
 *  keeps the factiii's id as a plain column. */
const VAULT_MODELS = [
  'Upload',
  'Post',
  'PostContent',
  'SearchVector',
  'MediaVector',
  'VaultFolder',
  'VaultShare',
  'PostFactiiiCount',
  'PostFactiii',
  'SpaceTime'
] as const;

type Block = { kind: 'model' | 'enum'; name: string; lines: string[] };

const HEADER = `// GENERATED by \`pnpm --filter @factiii/runner vault:schema\` from
// apps/server/prisma/schema.prisma. Do not edit: change the server's schema
// and run it again. Relations to models the vault does not keep are dropped;
// their id columns stay, as plain columns.

datasource db {
  provider   = "postgresql"
  extensions = [vector]
}

generator client {
  provider        = "prisma-client"
  output          = "./generated"
  moduleFormat    = "cjs"
  previewFeatures = ["postgresqlExtensions"]
}
`;

/** Every `model` and `enum` block, in file order. */
function readBlocks(schema: string): Block[] {
  const blocks: Block[] = [];
  let current: Block | null = null;
  for (const line of schema.split('\n')) {
    const open = /^(model|enum)\s+(\w+)\s*\{\s*$/.exec(line);
    if (open) {
      current = { kind: open[1] as Block['kind'], name: open[2], lines: [] };
      continue;
    }
    if (!current) continue;
    if (/^\}\s*$/.test(line)) {
      blocks.push(current);
      current = null;
      continue;
    }
    current.lines.push(line);
  }
  return blocks;
}

/** A field line's name and bare type (`Post[]?` -> `Post`), or null for a
 *  comment, a blank line or a block attribute. */
function fieldOf(line: string): { name: string; type: string } | null {
  const match = /^\s*(\w+)\s+(\w+)(\[\])?\??(\s|$)/.exec(line);
  if (!match || line.trim().startsWith('//') || line.trim().startsWith('@@')) {
    return null;
  }
  return { name: match[1], type: match[2] };
}

/** The field names a block attribute names: `@@index([a, b(sort: Desc)])`. */
function attributeFields(line: string): string[] {
  const list = /\[([^\]]*)\]/.exec(line);
  if (!list) return [];
  return list[1]
    .split(',')
    .map((part) => part.trim().replace(/\(.*$/, ''))
    .filter(Boolean);
}

/** One model with every relation to a model outside `keep` taken out, and
 *  the comment block written right above each dropped field with it. */
function pruneModel(
  block: Block,
  keep: ReadonlySet<string>,
  modelNames: ReadonlySet<string>
): string[] {
  const out: string[] = [];
  const dropped = new Set<string>();
  let comments: string[] = [];
  for (const line of block.lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('//')) {
      comments.push(line);
      continue;
    }
    const field = fieldOf(line);
    if (field && modelNames.has(field.type) && !keep.has(field.type)) {
      dropped.add(field.name);
      comments = [];
      continue;
    }
    if (trimmed.startsWith('@@')) {
      const names = attributeFields(trimmed);
      if (names.some((name) => dropped.has(name))) {
        comments = [];
        continue;
      }
    }
    out.push(...comments, line);
    comments = [];
  }
  out.push(...comments);
  return out;
}

/** The server's schema cut down to the vault: the vault models, the enums
 *  they use, and nothing else. Throws if a vault model is gone, so a rename
 *  on the server stops the generator instead of dropping a table. */
export function pruneSchema(
  serverSchema: string,
  models: readonly string[] = VAULT_MODELS
): string {
  const blocks = readBlocks(serverSchema);
  const modelNames = new Set(
    blocks.filter((b) => b.kind === 'model').map((b) => b.name)
  );
  const keep = new Set(models);
  const kept: string[] = [];
  const enums = new Set<string>();
  for (const name of models) {
    const block = blocks.find((b) => b.kind === 'model' && b.name === name);
    if (!block) throw new Error(`The server schema has no model ${name}.`);
    const lines = pruneModel(block, keep, modelNames);
    for (const line of lines) {
      const field = fieldOf(line);
      if (field && !modelNames.has(field.type) && /^[A-Z]/.test(field.type)) {
        enums.add(field.type);
      }
    }
    kept.push(`model ${name} {`, ...lines, '}', '');
  }
  for (const block of blocks) {
    if (block.kind !== 'enum' || !enums.has(block.name)) continue;
    kept.push(`enum ${block.name} {`, ...block.lines, '}', '');
  }
  return `${HEADER}\n${kept.join('\n').trimEnd()}\n`;
}
